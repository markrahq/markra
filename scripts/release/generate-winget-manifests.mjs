import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

// Use the schema supported by stable WinGet clients, including the Windows runner's client.
const manifestVersion = "1.10.0";

function findInstallers(root, name) {
  if (!fs.existsSync(root)) return [];

  return fs.readdirSync(root, { withFileTypes: true }).flatMap((entry) => {
    const filePath = path.join(root, entry.name);
    if (entry.isDirectory()) return findInstallers(filePath, name);
    return entry.isFile() && entry.name === name ? [filePath] : [];
  });
}

async function main() {
  const version = process.env.RELEASE_VERSION?.trim().replace(/^v/, "") || "";
  if (!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version)) {
    throw new Error("RELEASE_VERSION must be a stable version, for example v1.2.3.");
  }

  const configPath = process.env.TAURI_CONFIG_PATH || "apps/desktop/src-tauri/tauri.conf.json";
  const config = JSON.parse(fs.readFileSync(configPath, "utf8"));
  const installMode = config.bundle?.windows?.nsis?.installMode || "currentUser";
  if (installMode !== "currentUser") {
    throw new Error("WinGet manifests currently require the NSIS currentUser install mode.");
  }

  // Match Tauri's NSIS defaults, including its Add/Remove Programs publisher.
  const publisher = config.bundle?.publisher || config.identifier.split(".")[1] || config.identifier;
  const productName = config.productName;
  const fileName = `${productName}_${version}_windows_x64_setup.exe`;
  const installers = findInstallers(process.env.RELEASE_ASSETS_ROOT || "release-assets", fileName);
  if (installers.length !== 1) {
    throw new Error(`Expected exactly one Windows x64 NSIS installer named ${fileName}; found ${installers.length}.`);
  }

  const hash = crypto.createHash("sha256");
  for await (const chunk of fs.createReadStream(installers[0])) hash.update(chunk);
  const sha256 = hash.digest("hex").toUpperCase();
  const repository = process.env.GITHUB_REPOSITORY?.trim() || "markrahq/markra";
  const repositoryUrl = `https://github.com/${repository}`;
  const releaseUrl = `${repositoryUrl}/releases/tag/v${version}`;
  const installerUrl = `${repositoryUrl}/releases/download/v${version}/${encodeURIComponent(fileName)}`;
  const quote = JSON.stringify;
  const header = (type) => `# Generated by scripts/release/generate-winget-manifests.mjs
# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.${manifestVersion}.schema.json

PackageIdentifier: Markra.Markra
PackageVersion: ${quote(version)}
`;
  const footer = (type) => `ManifestType: ${type}
ManifestVersion: ${manifestVersion}
`;
  const manifests = {
    "Markra.Markra.yaml": `${header("version")}DefaultLocale: en-US
${footer("version")}`,
    "Markra.Markra.locale.en-US.yaml": `${header("defaultLocale")}PackageLocale: en-US
Publisher: ${quote(publisher)}
PublisherUrl: ${quote(`https://github.com/${repository.split("/")[0]}`)}
PublisherSupportUrl: ${quote(`${repositoryUrl}/issues`)}
PackageName: ${quote(productName)}
PackageUrl: ${quote(repositoryUrl)}
License: AGPL-3.0-only
LicenseUrl: ${quote(`${repositoryUrl}/blob/v${version}/LICENSE`)}
ShortDescription: AI-native Markdown editor
Moniker: markra
Tags:
  - editor
  - markdown
ReleaseNotesUrl: ${quote(releaseUrl)}
${footer("defaultLocale")}`,
    "Markra.Markra.installer.yaml": `${header("installer")}InstallerType: nullsoft
Scope: user
UpgradeBehavior: install
ProductCode: ${quote(productName)}
Installers:
  - Architecture: x64
    InstallerUrl: ${quote(installerUrl)}
    InstallerSha256: ${sha256}
${footer("installer")}`,
  };
  const outputDir = path.join(process.env.OUTPUT_DIR || "generated/winget", "manifests/m/Markra/Markra", version);
  fs.mkdirSync(outputDir, { recursive: true });
  for (const [name, content] of Object.entries(manifests)) {
    fs.writeFileSync(path.join(outputDir, name), content);
  }
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
